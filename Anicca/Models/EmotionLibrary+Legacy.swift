    /// Valence for a word as stored on a check-in. Tries the current library first (same center,
    /// then any center, in case the word moved), then the frozen v1 table.
    static func valence(forStoredName name: String, center: EnergyCenter) -> EmotionValence? {
        if let emotion = emotion(named: name, in: center) { return emotion.valence }
        if let emotion = all.first(where: { $0.name.caseInsensitiveCompare(name) == .orderedSame }) {
            return emotion.valence
        }
        return v1Valence[name.lowercased()]
    }
